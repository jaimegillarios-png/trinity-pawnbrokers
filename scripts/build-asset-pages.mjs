#!/usr/bin/env node
/**
 * Builds every asset page from its content file.
 *
 *   src/content/<slug>.js  +  src/templates/asset-page.mjs  ->  <slug>.html
 *
 * Run after editing any content file:   node scripts/build-asset-pages.mjs
 * Build one page only:                  node scripts/build-asset-pages.mjs watches
 *
 * The generated .html files are committed (this is a static site with no
 * server-side build), but they are OUTPUT — edit the content file, not the HTML.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve, basename } from 'node:path';
import assetPage from '../src/templates/asset-page.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = resolve(root, 'src/content');

const only = process.argv.slice(2);
const files = (await readdir(CONTENT)).filter((f) => f.endsWith('.js')).sort();
const targets = only.length ? files.filter((f) => only.includes(basename(f, '.js'))) : files;

if (!targets.length) {
  console.error(only.length ? `No content file for: ${only.join(', ')}` : 'No content files found.');
  process.exit(1);
}

const BANNER = '<!-- GENERATED by scripts/build-asset-pages.mjs — edit src/content/%s.js, not this file. -->\n';

let built = 0, unchanged = 0;
for (const file of targets) {
  const slug = basename(file, '.js');
  const mod = await import(pathToFileURL(resolve(CONTENT, file)).href + `?t=${built}`);
  const content = mod.default;

  if (content.slug !== slug) {
    console.error(`  ✗ ${file}: slug is "${content.slug}" but the file is named "${slug}.js"`);
    process.exit(1);
  }

  const html = BANNER.replace('%s', slug) + assetPage(content);
  const out = resolve(root, `${slug}.html`);
  const prev = await readFile(out, 'utf8').catch(() => null);

  // ?v= hashes are added afterwards by stamp-assets.mjs — ignore them here
  const bare = (x) => (x || '').replace(/\?v=[a-f0-9]+/g, '');
  if (bare(prev) === bare(html)) {
    unchanged++;
    console.log(`  = ${slug}.html (unchanged)`);
  } else {
    await writeFile(out, html, 'utf8');
    built++;
    const todos = (html.match(/TODO/g) || []).length;
    console.log(`  ✓ ${slug}.html${todos ? `  — ${todos} TODO${todos > 1 ? 's' : ''} still to write` : ''}`);
  }
}

console.log(`\n${built} written, ${unchanged} unchanged.`);
